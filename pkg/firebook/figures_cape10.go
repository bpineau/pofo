// The fit the plate draws and names: ordinary least squares of the ten-year
// real return on the earnings yield 100/CAPE, both in percent, over the 1 243
// pairs above. It is the article's own arithmetic (a rate of return regressed
// on a rate of return), and it is the specification stated on the plate.
// Regressing on ln(CAPE) instead gives R2 = 0.313, and stretching the horizon
// to fifteen years gives 0.355 (0.407 in logs): the article quotes both.
const (
	capeFitA  = 1.0559 // intercept, percent per year
	capeFitB  = 0.8598 // percent of return per point of earnings yield
	capeFitR2 = 0.2871
)

// capeBand is one narrow slice of the CAPE axis (centre +/- 10 %) and what the
// decade that followed actually paid inside it: the plate draws the full range
// as a wash column and the first-to-ninth-decile span as a bracket, so a reader
// sees the centre moving and the width staying in the same glance.
type capeBand struct {
	centre, lo, hi         float64
	n                      int
	min, d1, med, d9, max_ float64 // percent per year, real
}

// capeBands are recomputed by the guard test from the same arrays. Deciles are
// linearly interpolated on the sorted outcomes.
var capeBands = []capeBand{
	{10, 9.0, 11.0, 164, 2.67, 5.63, 10.20, 15.97, 18.88},
	{20, 18.0, 22.0, 219, -3.64, -1.96, 5.70, 11.37, 14.44},
	{30, 27.0, 33.0, 48, -2.54, -0.90, 2.81, 5.59, 9.56},
}

func figCapeDixAns() string {
	const (
		x0, x1     = 76.0, 604.0
		yTop, yBot = 112.0, 308.0
		cLo, cHi   = 4.0, 46.0
		vLo, vHi   = -7.0, 21.0
	)
	x := func(c float64) float64 { return x0 + (c-cLo)/(cHi-cLo)*(x1-x0) }
	y := func(v float64) float64 { return yBot - (v-vLo)/(vHi-vLo)*(yBot-yTop) }

	var b strings.Builder
	b.WriteString(plateHead("le centre bouge, la largeur reste",
		"Le CAPE d'un mois, et les dix années réelles qui l'ont suivi"))
	b.WriteString(sTxt(24, 62, 10.5, figMuted, "start", "400",
		"chaque point : un mois de départ, et le rendement réel annualisé du S&amp;P 500 sur les 120 mois suivants"))
	b.WriteString(sTxt(24, 78, 10.5, figMuted, "start", "400",
		"1 243 départs mensuels de janvier 1913 à juillet 2016, total return déflaté du CPI américain"))
	b.WriteString(sTxt(24, 100, 10, figMuted, "start", "400", "rendement réel annualisé, en % par an"))

	// Grid, the zero line carrying the weight.
	for _, g := range []float64{-5, 0, 5, 10, 15, 20} {
		col := figGrid
		if g == 0 {
			col = figRule
		}
		b.WriteString(line(x0, y(g), x1, y(g), col, 1))
		b.WriteString(mTxt(x0-8, y(g)+3.5, 10, figMuted, "end", "400", capeSigned(g, 0)))
	}

	// The three slices, drawn under the cloud: the wash column covers every
	// outcome of the slice, and its hairline edges keep it visible where the
	// cloud is thickest.
	for _, s := range capeBands {
		fmt.Fprintf(&b, `<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s" stroke="%s" stroke-width="1"/>`,
			x(s.lo), y(s.max_), x(s.hi)-x(s.lo), y(s.min)-y(s.max_), figWash, figRule)
	}

	// The cloud itself.
	for i, c := range capeStarts {
		fmt.Fprintf(&b, `<circle cx="%.1f" cy="%.1f" r="1.5" fill="%s"/>`,
			x(c), y(capeForward10[i]), figBlueTint)
	}

	// The fit, drawn only over the CAPE range the record actually holds.
	var fit [][2]float64
	for c := capeStarts[minIndex(capeStarts)]; c <= capeStarts[maxIndex(capeStarts)]+0.001; c += 0.25 {
		fit = append(fit, [2]float64{x(c), y(capeFitA + capeFitB*100/c)})
	}
	b.WriteString(poly(fit, figAccent, 2.4, ""))
	b.WriteString(sTxt(x1, 150, 10, figMuted, "end", "400", "ajustement des moindres carrés"))
	b.WriteString(mTxt(x1, 167, 10.5, figDeep, "end", "600", "rendement = 1,1 + 0,86 × 100 / CAPE"))
	b.WriteString(mTxt(x1, 184, 11, figDeep, "end", "600", "R² = 0,29"))

	// Axes.
	b.WriteString(line(x0, yTop, x0, yBot, figRule, 1))
	b.WriteString(line(x0, yBot, x1, yBot, figRule, 1))

	// What each slice paid: eight starts out of ten between the two caps. The
	// median reading goes to the side of the column the fit curve leaves free.
	for i, s := range capeBands {
		xc := (x(s.lo) + x(s.hi)) / 2
		tagX, tagY := x(s.hi)+29, y(s.med)+3.5
		if i == len(capeBands)-1 {
			tagY = y(s.med) + 13 // the fit curve grazes the last median, drop under it
		}
		b.WriteString(line(xc, y(s.d1), xc, y(s.d9), figInk, 2))
		b.WriteString(line(xc-5, y(s.d9), xc+5, y(s.d9), figInk, 2))
		b.WriteString(line(xc-5, y(s.d1), xc+5, y(s.d1), figInk, 2))
		b.WriteString(capeTag(xc, y(s.d9)-8, 34, figSoft, "400", capeSigned(s.d9, 1)))
		b.WriteString(capeTag(xc, y(s.d1)+15, 34, figSoft, "400", capeSigned(s.d1, 1)))
		fmt.Fprintf(&b, `<circle cx="%.1f" cy="%.1f" r="4" fill="%s" stroke="#fffdf9" stroke-width="1.6"/>`,
			xc, y(s.med), figDeep)
		b.WriteString(capeTag(tagX, tagY, 46, figDeep, "600", capeSigned(s.med, 1)+" %"))
	}

	// The CAPE axis: plain ticks, plus what each slice covers.
	for _, c := range []float64{5, 15, 25, 35, 45} {
		b.WriteString(line(x(c), yBot, x(c), yBot+4, figRule, 1))
		b.WriteString(mTxt(x(c), yBot+18, 10, figMuted, "middle", "400", fmt.Sprintf("%.0f", c)))
	}
	for _, s := range capeBands {
		xc := (x(s.lo) + x(s.hi)) / 2
		b.WriteString(sTxt(xc, yBot+18, 10, figSoft, "middle", "600",
			fmt.Sprintf("%.0f à %.0f", s.lo, s.hi)))
		b.WriteString(sTxt(xc, yBot+32, 9.5, figMuted, "middle", "400",
			fmt.Sprintf("%d départs", s.n)))
	}
	b.WriteString(sTxt((x0+x1)/2, yBot+52, 11, figMuted, "middle", "400", "CAPE au départ  →"))

	b.WriteString(sTxt(24, 388, 10.5, figSoft, "start", "600",
		"Le trait épais couvre huit départs sur dix, la colonne claire les couvre tous. À CAPE 9 à 11, la décennie"))
	b.WriteString(sTxt(24, 404, 10.5, figSoft, "start", "400",
		"a payé de +2,7 à +18,9 % réels par an ; à CAPE 18 à 22, de −3,6 à +14,4 %. Le centre descend, la largeur reste."))
	b.WriteString(sTxt(24, 420, 10.5, figMuted, "start", "400",
		"La colonne 27 à 33 ne compte que 48 départs (1929, la fin des années 1990, 2013-2015) : largeur sous-mesurée."))
	return svg(640, 440, b.String())
}

// capeTag prints a number over the cloud on a small opaque backing, so the dots
// never eat it. The backing is a solid card-coloured rect, never an opacity.
func capeTag(cx, cy, w float64, color, weight, s string) string {
	return fmt.Sprintf(`<rect x="%.1f" y="%.1f" width="%.1f" height="12.5" fill="#fffdf9"/>`,
		cx-w/2, cy-9.5, w) + mTxt(cx, cy, 9.5, color, "middle", weight, s)
}

// capeSigned formats a percentage the French way, with a true minus sign and a
// comma, and an explicit plus so a column of readings stays legible.
func capeSigned(v float64, decimals int) string {
	s := frNum(math.Abs(v), decimals)
	switch {
	case v > 0:
		return "+" + s
	case v < 0:
		return "−" + s
	}
	return s
}

func minIndex(v []float64) int {
	best := 0
	for i, x := range v {
		if x < v[best] {
			best = i
		}
	}
	return best
}

func maxIndex(v []float64) int {
	best := 0
	for i, x := range v {
		if x > v[best] {
			best = i
		}
	}
	return best
}
